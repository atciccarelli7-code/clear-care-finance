import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { createServer } from "vite";
import { repositoryRoot } from "./seo-route-utils.mjs";

const outputPath = path.join(repositoryRoot, "src", "data", "runtimeSeoManifest.ts");
const vite = await createServer({
  root: repositoryRoot,
  mode: "production",
  appType: "custom",
  logLevel: "error",
  server: { middlewareMode: true },
});

const assertUnique = (items, label) => {
  const slugs = items.map((item) => item.slug);
  const duplicates = slugs.filter((slug, index) => slugs.indexOf(slug) !== index);
  if (duplicates.length) throw new Error(`Duplicate ${label} SEO slugs: ${Array.from(new Set(duplicates)).join(", ")}`);
};

try {
  const [{ ALL_ARTICLES }, { TOPICS }, { tools }, { roadmapTools }] = await Promise.all([
    vite.ssrLoadModule("/src/data/allArticles.ts"),
    vite.ssrLoadModule("/src/data/topics.ts"),
    vite.ssrLoadModule("/src/data/tools.ts"),
    vite.ssrLoadModule("/src/data/roadmapTools.ts"),
  ]);

  const articles = ALL_ARTICLES.map((article) => ({
    slug: article.slug,
    title: article.title,
    description: article.description ?? article.promise,
    category: article.category,
    ...(article.publishedAt ? { publishedAt: article.publishedAt } : {}),
    ...(article.lastReviewedAt ? { lastReviewedAt: article.lastReviewedAt } : {}),
  }));
  const topics = TOPICS.map((topic) => ({
    slug: topic.slug,
    title: topic.title,
    description: topic.promise,
  }));
  const genericTools = [
    ...tools
      .filter((tool) => tool.componentKey && !tool.href)
      .map((tool) => ({ slug: tool.slug, title: tool.title, description: tool.description })),
    ...roadmapTools.map((tool) => ({ slug: tool.slug, title: tool.title, description: tool.description })),
  ];

  assertUnique(articles, "article");
  assertUnique(topics, "topic");
  assertUnique(genericTools, "tool");

  const articleRows = articles.map((article) => [
    article.slug,
    article.title,
    article.description,
    article.category,
    article.publishedAt ?? null,
    article.lastReviewedAt ?? null,
  ]);
  const topicRows = topics.map((topic) => [topic.slug, topic.title, topic.description]);
  const toolRows = genericTools.map((tool) => [tool.slug, tool.title, tool.description]);

  const source = `// Generated by scripts/generate-runtime-seo-manifest.mjs. Do not edit by hand.\n\n` +
    `export type RuntimeArticleSeoMeta = {\n  slug: string;\n  title: string;\n  description: string;\n  category: string;\n  publishedAt?: string;\n  lastReviewedAt?: string;\n};\n\n` +
    `export type RuntimeTopicSeoMeta = {\n  slug: string;\n  title: string;\n  description: string;\n};\n\n` +
    `export type RuntimeToolSeoMeta = {\n  slug: string;\n  title: string;\n  description: string;\n};\n\n` +
    `const ARTICLE_ROWS = ${JSON.stringify(articleRows, null, 2)} as const;\n` +
    `const TOPIC_ROWS = ${JSON.stringify(topicRows, null, 2)} as const;\n` +
    `const TOOL_ROWS = ${JSON.stringify(toolRows, null, 2)} as const;\n\n` +
    `export const RUNTIME_ARTICLE_SEO_META: RuntimeArticleSeoMeta[] = ARTICLE_ROWS.map(([slug, title, description, category, publishedAt, lastReviewedAt]) => ({\n` +
    `  slug, title, description, category,\n` +
    `  ...(publishedAt ? { publishedAt } : {}),\n` +
    `  ...(lastReviewedAt ? { lastReviewedAt } : {}),\n` +
    `}));\n\n` +
    `export const RUNTIME_TOPIC_SEO_META: RuntimeTopicSeoMeta[] = TOPIC_ROWS.map(([slug, title, description]) => ({ slug, title, description }));\n\n` +
    `export const RUNTIME_TOOL_SEO_META: RuntimeToolSeoMeta[] = TOOL_ROWS.map(([slug, title, description]) => ({ slug, title, description }));\n`;

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, source, "utf8");
  console.log(`Generated lightweight runtime SEO metadata for ${articles.length} articles, ${topics.length} topics, and ${genericTools.length} focused tools.`);
} finally {
  await vite.close();
}
